// Build declarative presets from reviewed data and the current bundled book.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { importBook } from '../src/core.js';
import { hash, assert } from '../src/primitives.js';
import { validateAdapter } from '../src/adapters.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=async name=>JSON.parse(await readFile(resolve(root,name),'utf8'));
const entries=importBook(await read('data/builtin-worldbook.json'));
const targets=await read('data/creation-targets.json'), configs=await read('data/creation-adapters.json');
for(const config of configs){
  const entry=entries.find(e=>e.name===targets[config.id]);assert(entry,'适配目标不存在：'+config.id);
  config.target.primaryHashes=[hash(entry.content)];
  assert(config.operations.every(o=>entry.content.includes(o.ruleQuote)),'适配操作依据已改变：'+entry.name);
  validateAdapter(config);
}
assert(new Set(configs.map(c=>c.id)).size===configs.length,'适配ID重复');
await writeFile(resolve(root,'data/creation-adapters.json'),JSON.stringify(configs,null,2)+'\n');
const compatibility=await read('data/creation-compatibility.json');
await writeFile(resolve(root,'src/creation-presets.js'),'// Generated by scripts/build-creation-presets.mjs; edit data/creation-adapters.json.\nexport const CREATION_PRESETS='+JSON.stringify(configs,null,2)+';\nexport const CREATION_PRESET_COMPATIBILITY='+JSON.stringify(compatibility,null,2)+';\n');
console.log(JSON.stringify({adapters:configs.length}));
