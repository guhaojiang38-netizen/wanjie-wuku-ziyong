// Offline build only. Reviewed rules come from the normalized current bundled book.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { assert, hash, importBook, inferResources } from '../src/core.js';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
assert(process.argv[2], 'Usage: node scripts/build-management-profiles.mjs original-worldbook.json');
const raw = await readFile(process.argv[2]), book = JSON.parse(raw.toString('utf8').replace(/^\uFEFF/, ''));
const entries = importBook(book, '万界武库V4.1'), input = JSON.parse(await readFile(resolve(root, 'data/management-recipes.json'), 'utf8'));
assert(input.schemaVersion === 1 && input.recipes.length === entries.length, '覆盖清单与原世界书数量不一致');
const names = new Set(), recipes = input.recipes.map(r => {
  const e = entries.find(e => e.entryId === r.entryId && e.name === r.name); assert(e && !names.has(r.name), `条目身份不存在或重复：${r.name}`); names.add(r.name);
  const resources = inferResources(e);
  assert(['primary', 'support'].includes(r.role) && r.templates.length <= 6 && (r.role === 'support' || r.templates.length), `模板数量无效：${r.name}`);
  for (const t of r.templates) {
    assert(['progress', 'arrangement', 'record'].includes(t.category) && t.ruleQuote.length >= 6 && t.ruleQuote.length <= 1200 && e.content.includes(t.ruleQuote), `模板没有原文依据：${r.name} / ${t.label}`);
    assert(!/余额|剩余次数|库存数量/.test(t.label) && !resources.some(v => t.label.includes(v.name)), `模板重复经济字段：${r.name} / ${t.label}`);
  }
  return { ...r, contentHash:hash(e.content), templates:r.templates.map((t, i) => ({ ...t, id:`template_${i}` })) };
});
const data = { schemaVersion:1, source:input.source, sourceSha256:createHash('sha256').update(raw).digest('hex'), entries:recipes };
await writeFile(resolve(root, 'src/management-profiles-data.js'), '// Generated by scripts/build-management-profiles.mjs; edit data/management-recipes.json.\nexport const PROFILE_DATA = '+JSON.stringify(data, null, 0)+';\n', 'utf8');
process.stdout.write(JSON.stringify({ entries:recipes.length, primary:recipes.filter(r=>r.role==='primary').length, support:recipes.filter(r=>r.role==='support').length, templates:recipes.reduce((n,r)=>n+r.templates.length,0), sourceSha256:data.sourceSha256 }));
