// Offline author-data build. Never execute embedded worldbook or regex scripts.
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { importBook } from '../src/core.js';
import { hash, stable, assert } from '../src/primitives.js';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
assert(process.argv[2] && process.argv[3] && process.argv[4], 'Usage: node scripts/build-worldbook.mjs latest.json previous.json previous-adapters.json');
const raw = await readFile(process.argv[2]);
const read = async path => JSON.parse((await readFile(path, 'utf8')).replace(/^\uFEFF/, ''));
const all = importBook(JSON.parse(raw.toString('utf8').replace(/^\uFEFF/, '')), '万界武库V4.1 · 内置');
// The author's export retains uid72 next to its replacement uid122.
const entries = all.filter(e => !(e.name === '升变之印' && e.entryId === '72' && all.some(n => n.name === e.name && n.entryId === '122')));
assert(new Set(entries.map(e => e.name)).size === entries.length, '仍有未审查的重复词条名称');
const aliases = { '绝对适应': '绝对适应（新版）', '自定义式': '自定义' };
const previous = importBook(await read(process.argv[3]), 'previous');
const legacy = previous.map(e => ({ name:e.name, entryId:e.entryId, contentHash:hash(e.content), length:e.content.length, target:aliases[e.name] || e.name }));
const adapters = await read(process.argv[4]);
const data = { version:'2026-10-11', sourceSha256:createHash('sha256').update(raw).digest('hex'), authorEntries:all.length, entries, legacy, legacyAdapterDigests:adapters.map(c=>hash(stable(c))) };
await writeFile(resolve(root, 'data/builtin-worldbook.json'), JSON.stringify({ name:'万界武库V4.1', entries:Object.fromEntries(entries.map(e=>[e.entryId,{uid:Number(e.entryId),comment:e.name,content:e.content,disable:!e.enabledInBook}])) },null,2)+'\n');
await writeFile(resolve(root, 'src/builtin-worldbook-data.js'), '// Generated by scripts/build-worldbook.mjs. Author text is data, never executable code.\nexport const BUILTIN_WORLDBOOK = '+JSON.stringify(data)+';\n');
console.log(JSON.stringify({authorEntries:all.length,builtinEntries:entries.length,sourceSha256:data.sourceSha256}));
